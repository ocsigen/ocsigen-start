-- The tables of Ocsigen Start (schema ocsigen_start): users, emails,
-- phones, activation links, groups, memberships and preregistrations,
-- with the triggers that keep users.main_email in sync with emails.
--
-- This file comes from the template of Ocsigen Start. `make db-update`
-- applies it, then the SQL file of the project. It can be applied as many
-- times as needed: on an empty database it creates the schema; on a
-- database created by Ocsigen Start 0.99 or later, or by the template of
-- August and September 2016 (tables in the public schema), it brings the
-- schema up to date; on an up-to-date database it changes nothing and
-- takes no lock on the tables. Everything happens in one transaction: on
-- error, nothing is changed.
--
-- Run it as the owner of the tables (DB_USER in Makefile.options; from
-- another role, SET ROLE or PGOPTIONS='-c role=...'), on PostgreSQL 9.6 or
-- later. The citext extension is created in the public schema if it is
-- not installed yet, which needs a superuser before PostgreSQL 13.
--
-- After an upgrade of Ocsigen Start, replace this file with the one of the
-- new template (lib/eliom/templates/os/ocsigen_start.sql in the opam
-- switch), back up the database and run `make db-update` again.
--
-- Do not edit this file: the tables of the application, and the columns it
-- adds to the tables below, belong to the SQL file of the project.
--
-- Groups that share a name (allowed before 2022) are merged into the
-- oldest one: the rows of every table that references them follow, the
-- descriptions of the other groups are dropped, and duplicate memberships
-- are removed (so are exact duplicates of any membership). The merge stops
-- with an explicit error when a table of the application references the
-- groups in a way it cannot rewrite: merge the groups by hand first.

\set ON_ERROR_STOP true
SET client_min_messages TO WARNING;

BEGIN;

-- One run at a time.
DO $$
  BEGIN
    PERFORM pg_advisory_xact_lock(hashtext('ocsigen_start.sql'));
  END;
$$;

-- Unqualified names (the citext type) resolve in the public schema,
-- whatever the search_path of the role or of the database; the schema of
-- the citext extension is added below.
SET LOCAL search_path TO public;

-- Existing databases. Before Ocsigen Start 0.99 (2016), the tables lived
-- in the public schema: they are moved to the schema ocsigen_start. A
-- table dropped by the project is created again further down.
DO $$
  DECLARE
    tables constant text[] :=
      ARRAY['users', 'emails', 'activation', 'groups', 'user_groups',
            'preregister'];
    -- A column each of these tables has had from the start, to tell them
    -- from tables of the application with the same name.
    keys constant text[] :=
      ARRAY['userid', 'email', 'activationkey', 'groupid', 'groupid',
            'email'];
    users regclass;
    owner text;
    i int;
  BEGIN
    IF to_regclass('ocsigen_start.users') IS NOT NULL THEN
      users := 'ocsigen_start.users';
    ELSIF to_regclass('public.users') IS NOT NULL
          AND (SELECT count(*) FROM pg_attribute
               WHERE attrelid = to_regclass('public.users')
                 AND attname IN ('userid', 'firstname')
                 AND NOT attisdropped) = 2
    THEN
      users := 'public.users';
      IF NOT EXISTS (SELECT 1 FROM pg_attribute
                     WHERE attrelid = users
                       AND attname = 'main_email' AND NOT attisdropped)
         OR (to_regclass('public.activation') IS NOT NULL
             AND NOT EXISTS (SELECT 1 FROM pg_attribute
                             WHERE attrelid = to_regclass('public.activation')
                               AND attname = 'validity'
                               AND NOT attisdropped))
      THEN
        RAISE EXCEPTION 'Databases created by the template of before 25 August 2016 (before Ocsigen Start 0.99) are not supported';
      END IF;
    ELSE
      IF to_regclass('public.os_users') IS NOT NULL THEN
        RAISE EXCEPTION 'Tables with the os_ prefix (Ocsigen Start of September 2016, never released) are not supported: rename them first';
      END IF;
      -- A new database (tables of the application that happen to have the
      -- names of ours are left alone).
      RETURN;
    END IF;
    SELECT pg_get_userbyid(relowner) INTO owner
      FROM pg_class WHERE oid = users;
    IF current_user <> owner THEN
      RAISE EXCEPTION 'Run this file as %, the owner of the Ocsigen Start tables (SET ROLE %, or PGOPTIONS=''-c role=%'' for make)', owner, owner, owner;
    END IF;
    IF to_regnamespace('ocsigen_start') IS NULL THEN
      CREATE SCHEMA ocsigen_start;
    END IF;
    FOR i IN 1 .. array_length(tables, 1) LOOP
      IF to_regclass('ocsigen_start.' || tables[i]) IS NULL
         AND to_regclass('public.' || tables[i]) IS NOT NULL
         AND EXISTS (SELECT 1 FROM pg_attribute
                     WHERE attrelid = to_regclass('public.' || tables[i])
                       AND attname = keys[i] AND NOT attisdropped)
      THEN
        EXECUTE format('ALTER TABLE public.%I SET SCHEMA ocsigen_start',
                       tables[i]);
      END IF;
    END LOOP;
  END;
$$;

CREATE SCHEMA IF NOT EXISTS ocsigen_start;

-- The citext extension, in the public schema unless it is installed
-- elsewhere already; its schema joins the search_path for the rest of the
-- transaction.
DO $$
  DECLARE
    ext_schema text;
  BEGIN
    SELECT n.nspname INTO ext_schema
      FROM pg_extension AS e
      JOIN pg_namespace AS n ON n.oid = e.extnamespace
     WHERE e.extname = 'citext';
    IF ext_schema IS NULL THEN
      CREATE EXTENSION citext WITH SCHEMA public;
      ext_schema := 'public';
    END IF;
    PERFORM set_config('search_path',
                       quote_ident(ext_schema) || ', public', true);
  END;
$$;

-- Note that main_email is not an emails foreign key, to prevent a circular
-- dependency. The triggers on the emails table keep this column in sync.
CREATE TABLE IF NOT EXISTS ocsigen_start.users (
       userid bigserial primary key,
       firstname text NOT NULL,
       lastname text NOT NULL,
       main_email citext,
       password text,
       avatar text,
       language text
);

CREATE TABLE IF NOT EXISTS ocsigen_start.emails (
       email citext primary key,
       userid bigint NOT NULL references ocsigen_start.users(userid),
       validated boolean NOT NULL DEFAULT(false)
);

CREATE TABLE IF NOT EXISTS ocsigen_start.activation (
       activationkey text primary key,
       userid bigint NOT NULL references ocsigen_start.users(userid),
       email citext NOT NULL,
       autoconnect boolean NOT NULL,
       validity bigint NOT NULL default 1,
       action text NOT NULL,
       data text NOT NULL,
       creationdate timestamp NOT NULL default (now() at time zone 'utc'),
       expiry timestamp
);

CREATE TABLE IF NOT EXISTS ocsigen_start.groups (
       groupid bigserial primary key,
       name text UNIQUE NOT NULL,
       description text
);

CREATE TABLE IF NOT EXISTS ocsigen_start.user_groups (
       userid bigint NOT NULL references ocsigen_start.users(userid),
       groupid bigint NOT NULL references ocsigen_start.groups(groupid)
);

CREATE TABLE IF NOT EXISTS ocsigen_start.preregister (
       email citext NOT NULL
);

CREATE TABLE IF NOT EXISTS ocsigen_start.phones (
       number citext primary key,
       userid bigint NOT NULL references ocsigen_start.users(userid)
);

-- Trigger functions. An email or a phone number can be deleted only if
-- the user keeps another way to connect; a new email becomes the main
-- email of a user who had none.
CREATE OR REPLACE FUNCTION ocsigen_start.can_delete_email ()
  RETURNS TRIGGER AS $$
  BEGIN
    IF (EXISTS (SELECT 1
                FROM ocsigen_start.emails, ocsigen_start.users
                WHERE emails.userid = old.userid
                  AND users.userid = old.userid
                  AND emails.email <> old.email
                  AND users.main_email = emails.email
                  AND validated))
    THEN
      RETURN old;
    ELSE
      RETURN NULL;
    END IF;
  END;
  $$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION ocsigen_start.can_delete_phone ()
  RETURNS TRIGGER AS $$
  BEGIN
    IF (EXISTS (SELECT 1
                FROM ocsigen_start.phones
                WHERE userid = old.userid AND number <> old.number) OR
        EXISTS (SELECT 1
                FROM ocsigen_start.emails
                WHERE userid = old.userid
                  AND validated))
    THEN
      RETURN old;
    ELSE
      RETURN NULL;
    END IF;
  END;
  $$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION ocsigen_start.set_main_email ()
  RETURNS TRIGGER AS $$
  BEGIN
    IF (EXISTS (SELECT 1
                FROM  ocsigen_start.users
                WHERE users.userid = NEW.userid
                  AND (users.main_email IS NULL OR
                       users.main_email NOT SIMILAR TO '%@%')))
    THEN
      UPDATE ocsigen_start.users
         SET main_email = NEW.email WHERE users.userid = NEW.userid;
    END IF;
    RETURN NEW;
  END;
  $$ LANGUAGE plpgsql;

-- The triggers, created when missing or bound to another function (the
-- templates before 9.0 defined these functions in the public schema, or
-- in the schema of the role). The functions they used are dropped once
-- no trigger uses them, as is the helper trigger_exists of those
-- templates.
DO $$
  DECLARE
    trg record;
    old_function oid;
    old_functions oid[] := '{}';
  BEGIN
    FOR trg IN
      SELECT * FROM (VALUES
        ('can_delete_phone', 'ocsigen_start.phones', 'BEFORE DELETE',
         'ocsigen_start.can_delete_phone()'),
        ('can_delete_email', 'ocsigen_start.emails', 'BEFORE DELETE',
         'ocsigen_start.can_delete_email()'),
        ('set_main_email', 'ocsigen_start.emails', 'AFTER INSERT',
         'ocsigen_start.set_main_email()'))
        AS t (name, tbl, event, fn)
    LOOP
      SELECT tgfoid INTO old_function
        FROM pg_trigger
       WHERE tgrelid = trg.tbl::regclass AND tgname = trg.name
         AND NOT tgisinternal;
      IF old_function = trg.fn::regprocedure THEN
        CONTINUE;
      END IF;
      IF old_function IS NOT NULL THEN
        EXECUTE format('DROP TRIGGER %I ON %s', trg.name, trg.tbl);
        old_functions := old_functions || old_function;
      END IF;
      EXECUTE format('CREATE TRIGGER %I %s ON %s FOR EACH ROW EXECUTE PROCEDURE %s',
                     trg.name, trg.event, trg.tbl, trg.fn);
    END LOOP;
    FOREACH old_function IN ARRAY old_functions LOOP
      IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgfoid = old_function)
      THEN
        EXECUTE format('DROP FUNCTION %s', old_function::regprocedure);
      END IF;
    END LOOP;
    DROP FUNCTION IF EXISTS public.trigger_exists (text);
  END;
$$;

-- Databases created by earlier releases. Each step checks the catalog
-- first, so that an up-to-date database gets no ALTER TABLE at all.
DO $$
  BEGIN
    -- Ocsigen Start 1.0 (2017): the language of the user.
    IF NOT EXISTS (SELECT 1 FROM pg_attribute
                   WHERE attrelid = 'ocsigen_start.users'::regclass
                     AND attname = 'language' AND NOT attisdropped)
    THEN
      ALTER TABLE ocsigen_start.users ADD COLUMN language text;
    END IF;
    -- 2018: a user may have no main email.
    IF EXISTS (SELECT 1 FROM pg_attribute
               WHERE attrelid = 'ocsigen_start.users'::regclass
                 AND attname = 'main_email' AND attnotnull)
    THEN
      ALTER TABLE ocsigen_start.users ALTER COLUMN main_email DROP NOT NULL;
    END IF;
    -- 2021: activation links expire; their creation date is a UTC
    -- timestamp without time zone, and their validity defaults to 1.
    IF NOT EXISTS (SELECT 1
                   FROM pg_attribute AS a
                   JOIN pg_attrdef AS d
                     ON d.adrelid = a.attrelid AND d.adnum = a.attnum
                   WHERE a.attrelid = 'ocsigen_start.activation'::regclass
                     AND a.attname = 'validity'
                     AND pg_get_expr(d.adbin, d.adrelid) = '1')
    THEN
      ALTER TABLE ocsigen_start.activation ALTER COLUMN validity SET DEFAULT 1;
    END IF;
    IF EXISTS (SELECT 1 FROM pg_attribute
               WHERE attrelid = 'ocsigen_start.activation'::regclass
                 AND attname = 'creationdate'
                 AND NOT attisdropped
                 AND format_type(atttypid, atttypmod)
                     = 'timestamp with time zone')
    THEN
      ALTER TABLE ocsigen_start.activation
        ALTER COLUMN creationdate TYPE timestamp
          USING (creationdate AT TIME ZONE 'utc'),
        ALTER COLUMN creationdate SET DEFAULT (now() AT TIME ZONE 'utc');
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_attribute
                   WHERE attrelid = 'ocsigen_start.activation'::regclass
                     AND attname = 'expiry' AND NOT attisdropped)
    THEN
      ALTER TABLE ocsigen_start.activation ADD COLUMN expiry timestamp;
    END IF;
  END;
$$;

-- 2022: group names are unique. Groups that share a name are merged into
-- the oldest one, as described at the top of this file. Nothing is done
-- when a unique index on the name already exists, whatever its name.
DO $$
  DECLARE
    fk record;
  BEGIN
    IF EXISTS (SELECT 1
               FROM pg_index AS i
               JOIN pg_attribute AS a
                 ON a.attrelid = i.indrelid AND a.attnum = i.indkey[0]
               WHERE i.indrelid = 'ocsigen_start.groups'::regclass
                 AND i.indisunique
                 AND i.indisvalid
                 AND i.indnatts = 1
                 AND i.indpred IS NULL
                 AND a.attname = 'name')
    THEN
      RETURN;
    END IF;
    -- References that cannot be rewritten below: a multi-column key, or a
    -- key on another column than groupid.
    SELECT c.conrelid::regclass AS tbl, c.conname INTO fk
      FROM pg_constraint AS c
     WHERE c.contype = 'f'
       AND c.confrelid = 'ocsigen_start.groups'::regclass
       AND (array_length(c.conkey, 1) <> 1
            OR c.confkey[1] <> (SELECT attnum FROM pg_attribute
                                WHERE attrelid = c.confrelid
                                  AND attname = 'groupid'))
     LIMIT 1;
    IF FOUND THEN
      RAISE EXCEPTION 'Cannot merge the groups that share a name: table % references ocsigen_start.groups through the constraint %, which this file cannot rewrite. Merge the groups by hand first.', fk.tbl, fk.conname;
    END IF;
    BEGIN
      -- Memberships that would be duplicated once the groups are merged:
      -- keep one per user and group name.
      DELETE FROM ocsigen_start.user_groups AS a
       USING ocsigen_start.user_groups AS b,
             ocsigen_start.groups AS ga,
             ocsigen_start.groups AS gb
       WHERE a.userid = b.userid
         AND a.ctid > b.ctid
         AND ga.groupid = a.groupid
         AND gb.groupid = b.groupid
         AND ga.name = gb.name;
      -- Every reference to a merged group, in user_groups as in the
      -- tables of the application, now points to the oldest group of
      -- that name.
      FOR fk IN
        SELECT c.conrelid::regclass AS tbl, a.attname AS col
          FROM pg_constraint AS c
          JOIN pg_attribute AS a
            ON a.attrelid = c.conrelid AND a.attnum = c.conkey[1]
         WHERE c.contype = 'f'
           AND c.confrelid = 'ocsigen_start.groups'::regclass
      LOOP
        EXECUTE format(
          'UPDATE %s AS r SET %I = kept.groupid
             FROM ocsigen_start.groups AS g
             JOIN (SELECT name, min(groupid) AS groupid
                     FROM ocsigen_start.groups GROUP BY name) AS kept
               ON kept.name = g.name
            WHERE r.%I = g.groupid AND g.groupid <> kept.groupid',
          fk.tbl, fk.col, fk.col);
      END LOOP;
      DELETE FROM ocsigen_start.groups AS g
       WHERE g.groupid <> (SELECT min(groupid)
                             FROM ocsigen_start.groups
                            WHERE name = g.name);
      ALTER TABLE ocsigen_start.groups
        ADD CONSTRAINT groups_name_key UNIQUE (name);
    EXCEPTION WHEN unique_violation THEN
      RAISE EXCEPTION 'Cannot merge the groups that share a name: %. Merge the groups by hand first.', SQLERRM;
    END;
  END;
$$;

COMMIT;
